"""Generate docs/MCP_TOOLS.md from the live server definition (names, descriptions, annotations, schemas)."""
import asyncio, json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from mcp.shared.memory import create_connected_server_and_client_session
from agritwin.mcp_server.server import build_server

async def main():
    server = build_server()
    async with create_connected_server_and_client_session(server._mcp_server) as c:
        tools = (await c.list_tools()).tools
        res = (await c.list_resource_templates()).resourceTemplates
        static = (await c.list_resources()).resources
        prompts = (await c.list_prompts()).prompts
    out = ["# AgriTwin MCP tool reference", "", "Generated by `python scripts/gen_tool_docs.py`. Mount the server with `agritwin-mcp` (stdio) or",
           "`agritwin-mcp --transport http`; it is also served at `/mcp/` by the API.", ""]
    kinds = {"read": [], "act": [], "gate": []}
    for t in tools:
        a = t.annotations
        kind = "gate" if a and a.destructiveHint else ("read" if a and a.readOnlyHint else "act")
        kinds[kind].append(t)
    for kind, title in (("read", "Read tools (readOnlyHint)"), ("act", "Act tools (write rows an officer sees; reach nobody outside)"),
                        ("gate", "The gate (destructiveHint · human only)")):
        out += [f"## {title}", ""]
        for t in kinds[kind]:
            props = (t.inputSchema or {}).get("properties", {})
            req = set((t.inputSchema or {}).get("required", []))
            args = ", ".join(f"{k}{'' if k in req else '?'}" for k in props) or "—"
            out += [f"### `{t.name}({args})`", "", (t.description or "").strip(), ""]
    out += ["## Resources", ""] + [f"* `{r.uri}` — {r.name}" for r in static] + [f"* `{r.uriTemplate}` — {r.name}" for r in res]
    out += ["", "## Prompts", ""] + [f"* `{p.name}` — {p.description}" for p in prompts]
    Path("docs/MCP_TOOLS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/MCP_TOOLS.md: {len(tools)} tools, {len(static)+len(res)} resources, {len(prompts)} prompts")

asyncio.run(main())
